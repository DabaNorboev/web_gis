test('late profile cannot overwrite a replacement or its map geometry on home', async ({ page, api }) => {
    await workspace(page)
    await page.addInitScript(id => {
        const fetch = window.fetch.bind(window)
        window.fetch = async (input, init) => {
            if (!String(input).includes(encodeURIComponent(id) + '/profile')) return fetch(input, init)
            const response = await fetch(input, { ...init, signal: undefined }), json = response.json.bind(response)
            response.json = async () => { const body = await json(); window.__homeLateRead = true; return body }
            return response
        }
    }, places.c.id)
    const gate = api.hold(places.c)
    await page.goto(`/?left=${encodeURIComponent(places.a.id)}&radius_m=500`)
    await expect(results(page).getByLabel('Состояние А')).toHaveAttribute('aria-busy', 'false')
    await chooseAddress(page, 'А', places.c); await gate.started
    await chooseAddress(page, 'А', places.d)
    await expect(results(page).getByLabel('Состояние А')).toHaveAttribute('aria-busy', 'false')
    gate.release(); await page.waitForFunction(() => window.__homeLateRead)
    await expect(results(page)).toContainText(places.d.label)
    await expect(results(page)).not.toContainText(places.c.label)
    if (test.info().project.use.viewport.width < 768) await page.getByRole('group', { name: 'Рабочая область', exact: true }).getByRole('button', { name: 'Карта', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => {
        const source = window.__smokeMapIn('.placelens-map')?.getSource('transport-selection')
        if (!source) return null
        return (await source.getData()).features.filter(feature => feature.properties.kind === 'address-object').map(feature => feature.properties.id)
    })).toEqual([places.d.id])
    expect(profiles(api)).toHaveLength(3)
})
