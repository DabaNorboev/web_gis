    await expect(results(page).getByLabel('Состояние Б')).toHaveAttribute('aria-busy', 'false')
    expect(profiles(api)).toHaveLength(3)
    expect(profiles(api).filter(url => url.includes(encodeURIComponent(places.a.id)))).toHaveLength(1)
