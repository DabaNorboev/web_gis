import { test, expect, homeScreen } from './support.mjs'
import { places } from './fixtures.mjs'
import { carResponse } from './fixtures/home-trips.mjs'

for (const viewport of [{ width: 1440, height: 900 }, { width: 1280, height: 560 }]) {
    test(`U2 map layout preserves state ${viewport.width}x${viewport.height}`, async ({ page, api }) => {
        await page.setViewportSize(viewport)
        await page.addInitScript(() => localStorage.setItem('placelens:interface:v1', 'workspace'))
        let posts = 0
        await page.route('**/api/v1/addresses/resolve-point', route => route.fulfill({ json: { data: { match: 'NONE', requires_choice: false, candidates: [] }, meta: { source: 'Synthetic', quality: {}, coverage: {} } } }))
        await page.route('**/api/v1/trips/analyze', route => { posts++; return route.fulfill({ json: carResponse(route.request().postDataJSON()) }) })
        const selection = { version: 1, mode: 'driving', places: [{ id: 'work', label: 'Работа', point: { lon: 92.91, lat: 56.03 } }, { id: 'study', label: 'Учёба', point: { lon: 92.89, lat: 56.04 } }], roads: {} }
        await page.goto('/?' + new URLSearchParams({ left: places.a.id, right: places.b.id, radius_m: '500' }) + '#' + new URLSearchParams({ places: JSON.stringify(selection) }))
        await expect(page.getByRole('button', { name: 'Показать маршрут', exact: true })).toHaveCount(4)
        await expect.poll(() => page.evaluate(() => window.__smokeMapIn('.placelens-map')?.loaded())).toBe(true)
        await page.evaluate(() => { window.__u2map = window.__smokeMapIn('.placelens-map'); window.__u2map.jumpTo({ center: [92.92, 56.02], zoom: 13 }) })
        const snapshot = () => page.evaluate(() => { const m = window.__smokeMapIn('.placelens-map'); return { same: m === window.__u2map, center: m.getCenter().toArray(), zoom: m.getZoom() } })
        const camera = await snapshot(), count = posts
        const name = page.getByLabel('Название места', { exact: true }).first()
        await name.fill('Работа черновик')
        const handle = page.getByRole('separator', { name: 'Высота карты' })
        const initial = Number(await handle.getAttribute('aria-valuenow'))
        expect(initial).toBe(960)
        expect(Math.round((await page.locator('.placelens-map').boundingBox()).height)).toBe(initial)
        await page.screenshot({ path: `experiments/placelens-visual/screenshots/v1-toolbar-before-${viewport.height}.png` })
        await handle.focus(); await handle.press('ArrowUp')
        await expect(handle).toHaveAttribute('aria-valuenow', String(initial - 16))
        const rect = await handle.boundingBox()
        await page.mouse.move(rect.x + rect.width / 2, rect.y + 6); await page.mouse.down(); await page.mouse.move(rect.x + rect.width / 2, rect.y - 54); await page.mouse.up()
        await expect(handle).toHaveAttribute('aria-valuenow', String(initial - 76))
        await page.getByRole('button', { name: 'Свернуть панель', exact: true }).click()
        await expect(page.locator('#home-panel')).toHaveAttribute('inert', '')
        expect((await page.locator('.placelens-map').boundingBox()).x).toBe(0)
        await expect(page.getByRole('button', { name: 'Показать панель' })).toBeInViewport()
        await page.screenshot({ path: `experiments/placelens-visual/screenshots/v1-toolbar-collapsed-${viewport.height}.png` })
        await page.getByRole('button', { name: 'Развернуть карту', exact: true }).click()
        await page.getByRole('button', { name: 'Свернуть карту', exact: true }).click()
        await expect(handle).toHaveAttribute('aria-valuenow', String(initial - 76))
        await page.setViewportSize({ width: 390, height: 844 })
        await homeScreen(page, 'Настройки'); await expect(name).toHaveValue('Работа черновик')
        await expect(page.getByRole('button', { name: 'Показать панель' })).not.toBeVisible()
        await homeScreen(page, 'Карта')
        await page.screenshot({ path: `experiments/placelens-visual/screenshots/v1-toolbar-mobile-${viewport.height}.png` })
        await page.setViewportSize(viewport)
        await page.getByRole('button', { name: 'Показать панель' }).click()
        await expect(name).toHaveValue('Работа черновик')
        await expect(name).toBeFocused()
        expect(Math.round((await page.locator('.placelens-map').boundingBox()).height)).toBe(initial - 76)
        await expect(page.getByRole('button', { name: 'Сбросить высоту' })).toHaveCount(0)
        await handle.press('Home'); await expect(handle).toHaveAttribute('aria-valuenow', '180')
        await handle.press('End'); await expect(handle).toHaveAttribute('aria-valuenow', await handle.getAttribute('aria-valuemax'))
        expect(await snapshot()).toEqual(camera); expect(posts).toBe(count)
        await expect(page.locator('.placelens-map canvas')).toHaveCount(1)
        await expect(page.getByRole('button', { name: 'Показать маршрут', exact: true })).toHaveCount(4)
    })
}
