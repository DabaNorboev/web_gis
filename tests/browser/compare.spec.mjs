test('an uncancellable late profile cannot restore previous metrics or real map geometry', async ({ page, api }) => {
    // Fault injection at the transport boundary: model a response which has
    // already escaped cancellation. Keep the actual fetch, API fixture, JSON
    // parsing and application stale-response guard.
    await page.addInitScript(id => {
        const fetch = window.fetch.bind(window)
        window.fetch = async (input, init) => {
            if (!String(input).includes(encodeURIComponent(id) + '/profile')) return fetch(input, init)
            const response = await fetch(input, { ...init, signal: undefined })
            const json = response.json.bind(response)
            response.json = async () => {
                const body = await json()
                window.__lateBodyRead = true
                return body
            }
            return response
        }
    }, places.c.id)
    const gate = api.hold(places.c)
    await page.goto(comparisonUrl())
    await ready(page)
    await replaceSide(page, 'А', places.c)
    await gate.started
    await expect(page.getByRole('region', { name: 'Вариант А', exact: true })).toHaveAttribute('aria-busy', 'true')
    await replaceSide(page, 'А', places.d)
    await ready(page)
    await page.getByRole('button', { name: 'На карту', exact: true }).press('Enter')
    await expectGeometry(page, places.d)
    gate.release()
    await page.waitForFunction(() => window.__lateBodyRead === true)
    await mapReady(page)
    await expectGeometry(page, places.d)
    await expect(page).toHaveURL(comparisonUrl(places.d, places.b))
    await expect(page.locator('#compare-map-left').locator('..').locator('.comparison-map-address')).toContainText(places.d.label)
    await page.getByRole('button', { name: 'К результатам', exact: true }).press('Enter')
    await expect(page.locator('[aria-label="Точек остановок в радиусе, вариант А"] strong')).toHaveText('13')
    await expect(page.locator('[aria-label="Точек остановок в радиусе, вариант Б"] strong')).toHaveText('7')
    await expect(page.getByRole('heading', { name: `А ${places.c.label}`, exact: true })).toHaveCount(0)
})

