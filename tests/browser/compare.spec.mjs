test('pair, common radius, explicit independent replacements, URL and history', async ({ page, api }) => {
    await page.goto(comparisonUrl())
    await ready(page)
    await expect(page.getByRole('heading', { name: `А ${places.a.label}`, exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: `Б ${places.b.label}`, exact: true })).toBeVisible()
    const rightRequests = () => api.calls.filter(url => url.includes(encodeURIComponent(places.b.id)) && url.includes('/profile')).length
    const rightCount = rightRequests()
    await page.getByRole('button', { name: 'Заменить адрес А', exact: true }).press('Enter')
    const input = page.getByRole('combobox', { name: 'Адрес в Красноярске', exact: true })
    await input.fill(places.c.label)
    await expect(page.getByRole('option')).toHaveCount(1)
    await expect(page).toHaveURL(comparisonUrl()) // typing and highlighting do not choose an address
    await input.press('ArrowDown')
    await expect(page).toHaveURL(comparisonUrl())
    await input.press('Enter')
    await ready(page)
    await expect(page).toHaveURL(comparisonUrl(places.c, places.b))
    await expect(page.getByRole('heading', { name: `Б ${places.b.label}`, exact: true })).toBeVisible()
    expect(rightRequests()).toBe(rightCount)
    await page.getByRole('button', { name: '300 м', exact: true }).press('Enter')
    await ready(page)
    await expect(page).toHaveURL(comparisonUrl(places.c, places.b, 300))
    expect(api.calls.filter(url => url.endsWith('/profile?radius_m=300'))).toHaveLength(2)
    const leftCount = api.calls.filter(url => url.includes(encodeURIComponent(places.c.id)) && url.includes('/profile')).length
    await replaceSide(page, 'Б', places.d)
    await ready(page)
    await expect(page).toHaveURL(comparisonUrl(places.c, places.d, 300))
    await expect(page.getByRole('heading', { name: `А ${places.c.label}`, exact: true })).toBeVisible()
    expect(api.calls.filter(url => url.includes(encodeURIComponent(places.c.id)) && url.includes('/profile'))).toHaveLength(leftCount)
    await page.goBack()
    await ready(page)
    await expect(page).toHaveURL(comparisonUrl(places.c, places.b, 300))
    await page.goBack()
    await ready(page)
    await expect(page.getByRole('button', { name: '500 м', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.goForward()
    await ready(page)
    await expect(page).toHaveURL(comparisonUrl(places.c, places.b, 300))
    await page.reload()
    await ready(page)
    await expect(page.getByRole('heading', { name: `А ${places.c.label}`, exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: `Б ${places.b.label}`, exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '300 м', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: 'На карту', exact: true }).press('Enter')
    await expectGeometry(page, places.c)
})

test('adjacent neighbourhoods share scale, retain independent centers, split, overlays and reading focus', async ({ page, api }, testInfo) => {
    await page.goto(comparisonUrl()); await ready(page)
    const reading = page.getByRole('button', { name: 'Вода: на карте А', exact: true })
    await reading.focus()
    await page.getByRole('button', { name: 'На карту', exact: true }).press('Enter')
    await mapReady(page)
    await expect.poll(() => page.evaluate(() => {
        const visible = ['left', 'right'].map(side => window.__smokeMapIn(`#compare-map-${side}`)).filter(map => map.getContainer().clientWidth > 0)
        const expected = Math.min(...visible.map(map => {
            const center = map.getCenter(), extent = .005
            return map.cameraForBounds([[center.lng - extent, center.lat - extent], [center.lng + extent, center.lat + extent]], { padding: { top: 55, bottom: 55, left: 40, right: 40 }, maxZoom: 16 }).zoom
        }))
        return visible.every(map => Math.abs(map.getZoom() - expected) < .001)
    }), { message: 'initial common zoom fits the actual settled canvases, excluding hidden mobile pane dimensions' }).toBe(true).catch(async error => {
        const dimensions = await page.evaluate(() => ['left','right'].map(side => { const map=window.__smokeMapIn(`#compare-map-${side}`); const center=map.getCenter(); return {side, zoom:map.getZoom(), width:map.getContainer().clientWidth,height:map.getContainer().clientHeight, expected:map.cameraForBounds([[center.lng-.005,center.lat-.005],[center.lng+.005,center.lat+.005]],{padding:{top:55,bottom:55,left:40,right:40},maxZoom:16})} }))
        throw Error(error.message + '\n' + JSON.stringify(dimensions))
    })
    await page.locator('.comparison-map-return').press('Enter')
    await reading.focus()
    // Focusing the sticky map-entry button can itself scroll the sidebar.
    // Bookmark the actual reading position at entry, after that native focus movement.
    await page.getByRole('button', { name: 'На карту', exact: true }).focus()
    const readingPosition = await reading.boundingBox()
    const calls = api.calls.length, url = page.url()
    await page.getByRole('button', { name: 'На карту', exact: true }).press('Enter')
    await expect(page.getByRole('heading', { name: 'Окружение на карте', exact: true })).toBeFocused()
    await expectMapFits(page)
    const desktop = page.viewportSize().width >= 1100
    const frame = side => page.locator(`#compare-map-${side}`)
    if (desktop) {
        await expect(frame('left')).toBeVisible(); await expect(frame('right')).toBeVisible()
        const left = await frame('left').boundingBox(), right = await frame('right').boundingBox()
        expect(right.x).toBeGreaterThan(left.x + left.width)
        expect(left.height).toBeGreaterThan(200); expect(right.height).toBeGreaterThan(200)
        const divider = page.getByRole('separator', { name: 'Ширина карт А и Б' })
        await divider.press('ArrowLeft'); await expect(divider).toHaveAttribute('aria-valuenow', '48')
        const box = await divider.boundingBox()
        await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down()
        await page.mouse.move(box.x - 1000, box.y + box.height / 2); await page.mouse.up()
        expect((await frame('left').boundingBox()).width).toBeGreaterThanOrEqual(299)
        await divider.press('End'); expect((await frame('right').boundingBox()).width).toBeGreaterThanOrEqual(299)
        await divider.press('Home'); expect((await frame('left').boundingBox()).width).toBeGreaterThanOrEqual(299)
        await page.getByRole('button', { name: 'К радиусу', exact: true }).click()
        await expect(divider).toHaveAttribute('aria-valuenow', '50')
    } else {
        await expect(frame('left')).toBeVisible(); await expect(frame('right')).toBeHidden()
        await page.getByRole('button', { name: 'Карта Б', exact: true }).press('Enter')
        await expect(frame('right')).toBeVisible(); await expect(frame('left')).toBeHidden()
        await expectGeometry(page, places.b)
    }
    await mapReady(page)
    const readCameras = () => page.evaluate(() => ['left', 'right'].map(side => {
        const map = window.__smokeMapIn(`#compare-map-${side}`)
        return { zoom: map.getZoom(), center: map.getCenter().toArray(), bearing: map.getBearing(), pitch: map.getPitch() }
    }))
    const initial = await readCameras()
    expect(initial[0].center[0]).toBeCloseTo(places.a.lon, 4); expect(initial[1].center[0]).toBeCloseTo(places.b.lon, 4)
    await page.locator('.comparison-map-pane:visible').last().getByRole('button', { name: 'Приблизить', exact: true }).click()
    await mapReady(page)
    const zoomed = await readCameras()
    expect(zoomed[0].zoom).toBeCloseTo(zoomed[1].zoom, 7)
    expect(zoomed[0].zoom).toBeGreaterThan(initial[0].zoom)
    for (let index = 0; index < 2; index++) for (let coordinate = 0; coordinate < 2; coordinate++) expect(zoomed[index].center[coordinate]).toBeCloseTo(initial[index].center[coordinate], 9)
    // Rotation and pitch through the same real MapLibre event boundary.
    await page.evaluate(() => window.__smokeMap().jumpTo({ bearing: 25, pitch: 20 }))
    await expect.poll(async () => (await readCameras()).map(c => [c.bearing, c.pitch])).toEqual([[25, 20], [25, 20]])
    const cameraBeforeLayers = await readCameras()
    const bounds = await frame(desktop ? 'left' : 'right').boundingBox()
    await page.getByRole('button', { name: /Слои 0 включено/ }).press('Enter')
    await page.getByRole('checkbox', { name: 'Остановки', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Парки', exact: true }).check()
    await page.getByText('Дополнительные', { exact: true }).click()
    const info = page.getByRole('button', { name: 'О данных: Железнодорожные линии', exact: true })
    await info.press('Enter'); await expect(info).toHaveAttribute('aria-expanded', 'true')
    expect(await frame(desktop ? 'left' : 'right').boundingBox()).toEqual(bounds)
    await expectMapFits(page)
    await info.press('Escape'); await expect(info).toHaveAttribute('aria-expanded', 'false'); await expect(info).toBeFocused()
    await info.press('Escape'); await expect(page.getByRole('button', { name: /Слои 2 включено/ })).toBeFocused()
    for (const theme of ['Тёмная', 'Улицы', 'Светлая']) {
        await page.getByRole('group', { name: 'Тема подложки карты' }).getByRole('button', { name: theme, exact: true }).press('Enter')
        await mapReady(page)
        expect(await readCameras()).toEqual(cameraBeforeLayers)
        expect(api.calls).toHaveLength(calls); expect(page.url()).toBe(url)
    }
    // Selection is independent and survives view and theme changes.
    const stop = await page.evaluate(async () => {
        const map = window.__smokeMap(), data = await map.getSource('transport-selection').getData()
        const point = map.project(data.features.find(f => f.properties.kind === 'stop').geometry.coordinates), r = map.getCanvas().getBoundingClientRect()
        return { x: r.left + point.x, y: r.top + point.y }
    })
    await page.mouse.click(stop.x, stop.y)
    await expect(page.locator('.comparison-map-pane:visible .city-map-object')).toContainText(['Выбранная остановка'])
    await testInfo.attach('adjacent-maps', { body: await page.screenshot({ path: testInfo.outputPath('adjacent-maps.png') }), contentType: 'image/png' })
    await mapReady(page)
    const cameraAfterSelection = await readCameras()
    const canvas = await frame(desktop ? 'left' : 'right').locator('canvas').elementHandle()
    await page.getByRole('button', { name: 'К результатам', exact: true }).press('Enter')
    await expect(reading).toBeFocused()
    expect((await reading.boundingBox()).y).toBeCloseTo(readingPosition.y, 0)
    await page.getByRole('button', { name: 'На карту', exact: true }).press('Enter'); await mapReady(page)
    expect(await canvas.evaluate(el => el.isConnected)).toBe(true)
    expect(await readCameras()).toEqual(cameraAfterSelection)
    expect(api.calls).toHaveLength(calls)
    await page.getByRole('button', { name: 'К радиусу', exact: true }).click(); await mapReady(page)
    await expect.poll(async () => (await readCameras()).map(camera => [camera.bearing, camera.pitch])).toEqual([[0, 0], [0, 0]])
    const reset = await readCameras()
    expect(reset[0].bearing).toBe(0); expect(reset[1].pitch).toBe(0)
    expect(reset[0].center[0]).toBeCloseTo(places.a.lon, 4); expect(reset[1].center[0]).toBeCloseTo(places.b.lon, 4)
})

