import { test, expect, ready, mapReady, expectMapFits } from './support.mjs'
import { ambiguousGroup, ambiguousPlaces, places, comparisonUrl } from './fixtures.mjs'

test('address numbers, pointer and keyboard agree between list, labels and exact source objects', async ({ page, api }, testInfo) => {
    await page.goto('/')
    const input = page.getByRole('combobox', { name: 'Адрес в Красноярске', exact: true })
    await input.fill(ambiguousGroup.label)
    await expect(page.getByRole('option')).toHaveCount(1)
    await input.press('ArrowDown'); await input.press('Enter')
    const list = page.getByRole('list', { name: 'Объекты выбранного адреса' })
    await expect(list.getByRole('button')).toHaveCount(10)
    await expect(page.locator('.map-address-label')).toHaveCount(10)
    for (let index = 0; index < 10; index++) {
        const id = ambiguousPlaces[index].id
        await expect(list.locator(`[data-address-id="${id}"]`)).toHaveAttribute('data-object-number', String(index + 1))
        await expect(page.locator(`.map-address-label[data-address-id="${id}"]`)).toHaveText(String(index + 1))
    }
    await list.getByRole('button').nth(0).press('ArrowDown')
    await expect(list.getByRole('button').nth(1)).toBeFocused()
    await expect(page.locator('.map-address-label.is-highlighted')).toHaveAttribute('data-address-id', ambiguousPlaces[1].id)
    await expect(page.locator('.map-address-label.is-selected')).toHaveCount(0)
    await expect.poll(() => page.evaluate(() => {
        const map = window.__smokeMapIn('.placelens-map')
        return !!map && map.loaded() && !map.isMoving()
    })).toBe(true)
    const marker = page.locator(`.map-address-label[data-address-id="${ambiguousPlaces[9].id}"]`)
    await marker.hover()
    await expect(list.locator('.is-highlighted')).toHaveAttribute('data-address-id', ambiguousPlaces[9].id)
    const markers = await page.locator('.map-address-label').evaluateAll(elements => elements.map(element => { const r = element.getBoundingClientRect(); return { left:r.left,top:r.top,right:r.right,bottom:r.bottom } }))
    for (const [i, a] of markers.entries()) for (const b of markers.slice(i + 1)) expect(a.right <= b.left || b.right <= a.left || a.bottom <= b.top || b.bottom <= a.top).toBe(true)
    expect(api.calls.filter(url => url.includes('/profile'))).toHaveLength(0)
    await expect.poll(() => page.evaluate(async () => (await window.__smokeMapIn('.placelens-map').getSource('transport-selection').getData()).features.filter(feature => feature.properties.kind === 'address-object').map(feature => [feature.properties.id, feature.properties.number, feature.geometry]))).toEqual(ambiguousGroup.objects.map((object, index) => [object.id, index + 1, object.geometry]))
    await testInfo.attach('numbered-address-choice', { body: await page.screenshot({path:testInfo.outputPath('numbered-address-choice.png')}), contentType:'image/png' })
    await marker.press('Enter')
    await expect(page).toHaveURL(new RegExp(`/address/${encodeURIComponent(ambiguousPlaces[9].id)}`))
    await expect(page.getByRole('heading', { name: ambiguousPlaces[9].label, exact: true })).toBeVisible()
})

test('category action, exact object selection and theme persistence keep the chosen address and URL', async ({ page, api }) => {
    await page.goto(comparisonUrl())
    await ready(page)
    const url = page.url(), calls = api.calls.length
    await page.getByRole('button', { name: 'Ближайший парк: на карте Б', exact: true }).press('Enter')
    await mapReady(page)
    await expect(page.locator('.comparison-map-split')).toHaveAttribute('data-active-side','right')
    await expect(page.locator('#compare-map-right .map-address-label.is-selected')).toHaveText('Б')
    await expect(page.locator('#compare-map-right .city-map-object')).toContainText(places.b.label)
    await page.getByRole('button',{name:'Снять выделение объекта слоя',exact:true}).click()
    await mapReady(page)
    const point = await page.evaluate(() => {
        const map = window.__smokeMap(), p = map.project([92.887,56.018]), rect = map.getCanvas().getBoundingClientRect()
        return { x:rect.left+p.x,y:rect.top+p.y }
    })
    await page.mouse.click(point.x,point.y)
    await expect(page.locator('#compare-map-right .city-map-object')).toContainText(places.b.label)
    const selected = await page.evaluate(async () => (await window.__smokeMap().getSource('analysis-object-selection').getData()).features)
    const original = await page.evaluate(async () => (await window.__smokeMap().getSource('area-parks').getData()).features)
    expect(selected).toEqual(original)
    await page.getByRole('button', { name:'Тёмная', exact:true }).press('Enter')
    await expect(page.locator('#compare-map-right .city-map-object')).toContainText(places.b.label)
    expect(api.calls).toHaveLength(calls)
    expect(page.url()).toBe(url)
    await expectMapFits(page)
    await page.reload(); await ready(page)
    await page.getByRole('button',{name:'На карту',exact:true}).click()
    await mapReady(page)
    await expect(page.getByRole('button',{name:'Тёмная',exact:true})).toHaveAttribute('aria-pressed','true')
    await expect(page.locator('#compare-map-right .city-map')).toHaveAttribute('data-map-theme','dark')
    await expect(page.getByRole('button',{name:/Слои 0 включено/})).toBeVisible()
})

test('profile retains the selected stop and layers across themes and restores a repeated stop choice after nearest-object inspection', async ({ page, api }) => {
    await page.goto(`/address/${encodeURIComponent(places.a.id)}?radius_m=500`)
    await expect(page.getByRole('heading',{name:places.a.label,exact:true})).toBeVisible()
    await page.getByText('Другие остановки и число в круге',{exact:true}).click()
    const stop=page.getByRole('list',{name:'Остальные остановки профиля'}).getByRole('button').first()
    await stop.click()
    await expect(page.locator('.city-map-object')).toContainText('Выбранная остановка')
    await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Ближайший парк',exact:true})}).getByRole('button',{name:'Показать объект на карте',exact:true}).click()
    await expect(page.locator('.city-map-object')).toContainText(places.a.label)
    await expect.poll(()=>page.evaluate(()=>{const m=window.__smokeMapIn('.address-map');return !!m&&m.loaded()&&!m.isMoving()})).toBe(true)
    const before=await page.evaluate(async()=>{const m=window.__smokeMapIn('.address-map');return {data:await m.getSource('analysis-object-selection').getData(),zoom:m.getZoom(),center:m.getCenter().toArray()}})
    const calls=api.calls.length, url=page.url()
    for(const theme of ['Тёмная','Улицы','Светлая']) {
        await page.getByRole('button',{name:theme,exact:true}).click()
        await expect(page.locator('.city-map-object')).toContainText(places.a.label)
        await expect(stop).toHaveAttribute('aria-pressed','false')
        expect(await page.evaluate(async()=>{const m=window.__smokeMapIn('.address-map');return {data:await m.getSource('analysis-object-selection').getData(),zoom:m.getZoom(),center:m.getCenter().toArray()}})).toEqual(before)
        expect(api.calls).toHaveLength(calls);expect(page.url()).toBe(url)
    }
    await stop.click()
    await expect(page.locator('.city-map-object')).toContainText('Выбранная остановка')
    await expect.poll(()=>page.evaluate(async()=> (await window.__smokeMapIn('.address-map').getSource('analysis-object-selection').getData()).features.length)).toBe(0)
})

test('basemap failure remains explicit and retry preserves local layers, selection and camera', async ({ page, api }) => {
    // Fail an actual background-source request, including the initial load.
    await page.route('**/smoke-background.json', route => route.abort('connectionfailed'))
    await page.goto(comparisonUrl()); await ready(page)
    await page.getByRole('button',{name:'На карту',exact:true}).click(); await mapReady(page, true)
    await expect(page.locator('#compare-map-left').getByRole('status').filter({hasText:'Подложка загружена не полностью'})).toBeVisible()
    await expect(page.locator('.comparison-map-pane:visible .map-address-label.is-selected')).toHaveCount(page.viewportSize().width >= 1100 ? 2 : 1)
    await page.getByRole('button',{name:/Слои 0 включено/}).click()
    await page.getByRole('checkbox',{name:'Остановки',exact:true}).check()
    await page.getByRole('button',{name:/Слои 1 включено/}).click()
    await mapReady(page, true)
    const stop = await page.evaluate(async () => {
        const map=window.__smokeMap(), data=await map.getSource('transport-selection').getData(), feature=data.features.find(f=>f.properties.kind==='stop'), p=map.project(feature.geometry.coordinates), r=map.getCanvas().getBoundingClientRect()
        return {x:r.left+p.x,y:r.top+p.y}
    })
    await page.mouse.click(stop.x,stop.y)
    await expect(page.locator('.city-map-object')).toContainText('Выбранная остановка')
    await mapReady(page, true)
    const before=await page.evaluate(async()=>{const m=window.__smokeMap();return {data:await m.getSource('transport-selection').getData(),zoom:m.getZoom(),center:m.getCenter().toArray()}})
    const calls=api.calls.length
    await expect(page.locator('#compare-map-left').getByRole('status').filter({hasText:'Подложка загружена не полностью'})).toBeVisible()
    await page.unroute('**/smoke-background.json')
    await page.locator('#compare-map-left').getByRole('button',{name:'Повторить загрузку подложки',exact:true}).click()
    if (page.viewportSize().width >= 1100) await page.locator('#compare-map-right').getByRole('button',{name:'Повторить загрузку подложки',exact:true}).click()
    await mapReady(page)
    expect(await page.evaluate(async()=>{const m=window.__smokeMap();return {data:await m.getSource('transport-selection').getData(),zoom:m.getZoom(),center:m.getCenter().toArray()}})).toEqual(before)
    await expect(page.locator('.city-map-object')).toContainText('Выбранная остановка')
    expect(api.calls).toHaveLength(calls)
})
