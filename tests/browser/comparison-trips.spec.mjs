function result(value, index, options = {}) {
    const start = value.start, target = value.places[index], location = options.location
    const choice = end => ({ status: options.ambiguity && (!value[end === 'start' ? 'start' : 'places'][end === 'start' ? 'road' : index]?.road) ? 'CHOOSE' : 'SELECTED', point: null, candidates: [] })
    const snap = p => ({ original: p, matched: p.road ?? { lon: p.lon + .00001, lat: p.lat }, distance_m: 1 })
    const road_choices = { start: { ...choice('start'), status: options.ambiguity && !start.road ? 'CHOOSE' : 'SELECTED', point: snap(start).matched, candidates: options.ambiguity ? alternatives : [] }, target: { status: options.ambiguity && !target.road ? 'CHOOSE' : 'SELECTED', point: snap(target).matched, candidates: options.ambiguity ? alternatives.map(c => ({ ...c, point: { lon: target.lon + c.point.lon - 92.87, lat: target.lat } })) : [] } }
    const waiting = options.ambiguity && (!start.road || !target.road)
    const failure = waiting ? (!start.road && !target.road ? 'both_endpoints' : !start.road ? 'start' : 'target') : location
    return { index, label: target.label, start, target, status: failure ? waiting ? 'NEEDS_REFINEMENT' : 'UNKNOWN' : 'AVAILABLE', reason: 'Синтетический текст упоминает старт, но не устанавливает локализацию.', checks: [],
        diagnostics: { version: 1, issues: failure ? [{ code: waiting ? 'SNAP_CHOICE_REQUIRED' : 'SYNTHETIC', category: waiting ? 'ambiguity' : options.category || 'obstacle', stage: 'snap', location: failure, target_index: ['target', 'both_endpoints'].includes(failure) ? index : null }] : [] },
        route: failure ? null : { geometry: { type: 'LineString', coordinates: [[snap(start).matched.lon, start.lat], [snap(target).matched.lon, target.lat]] }, distance_m: start.lon < 92.88 ? 1450 : 2100, duration_s: 390 },
        snaps: failure ? null : { start: snap(start), target: snap(target) }, road_choices,
        metrics: { distance: { value: failure ? null : 1450 }, duration: { value: failure ? null : 390 } } }
}
function response(value, options = {}) { return { mode: 'driving', start: value.start, results: value.places.map((_, i) => result(value, i, typeof options === 'function' ? options(i) : options)), source: { name: 'Synthetic OSM', engine: 'OSRM', dataset_version: 'test', observed_at: null }, limitation: 'Синтетический снимок. Парковка и подход не рассчитаны.' } }
async function install(page) {
    const calls = []; let reply = value => response(value)
    await page.route('**/api/v1/addresses/resolve-point', route => route.fulfill({ json: { data: { match: 'NONE', requires_choice: false, candidates: [] }, meta: { source: 'Synthetic', quality: {}, coverage: {} } } }))
    await page.route('**/api/v1/trips/analyze', async route => {
        const request = route.request(), value = request.postDataJSON(); calls.push({ value, url: request.url(), headers: request.headers() })
        const result = await reply(value)
        return route.fulfill(result === 'error' ? { status: 503, json: {} } : { json: result })
    })
    return { calls, respond(fn) { reply = fn } }
}
