import { test, expect, ready, mapReady } from './support.mjs'
import { places, profile, comparisonUrl } from './fixtures.mjs'
const profileUrl = `/address/${encodeURIComponent(places.a.id)}?radius_m=500`
async function settled(page, selector = '.address-map') {
    await expect.poll(() => page.evaluate(selector => { const m = window.__smokeMapIn(selector); return !!m && m.loaded() && !m.isMoving() }, selector)).toBe(true)
}
async function camera(page, selector = '.address-map') {
    await settled(page, selector)
    return page.evaluate(selector => { const m = window.__smokeMapIn(selector); return { center:m.getCenter().toArray(), zoom:m.getZoom() } }, selector)
}
async function fitsSelection(page, selector = '.address-map') {
    await settled(page, selector)
    expect(await page.evaluate(async selector => {
        const map=window.__smokeMapIn(selector), coords=[]
        const collect=v=>typeof v[0]==='number'?coords.push(v):v.forEach(collect)
        const data=await map.getSource('transport-selection').getData()
        data.features.filter(f=>['point','selected-stop'].includes(f.properties.kind)).forEach(f=>collect(f.geometry.coordinates))
        const selected=await map.getSource('analysis-object-selection').getData()
        selected.features.forEach(f=>collect(f.geometry.coordinates))
        const frame=map.getCanvas().getBoundingClientRect()
        const card=document.querySelector(`${selector} .city-map-object`)?.getBoundingClientRect()
        return coords.length>=2 && coords.every(c=>{const p=map.project(c);return p.x>=30&&p.x<=frame.width-40&&p.y>=(selector.startsWith('#compare')?50:100)&&p.y<=frame.height-40}) && (!card||card.top>=frame.bottom-1)
    },selector)).toBe(true)
}
test('explicit stop and territory keep exact source geometry with the analysis point; hover, focus, close, layers and themes preserve camera', async ({page,api}) => {
    await page.goto(profileUrl)
    await expect(page.getByRole('heading',{name:places.a.label,exact:true})).toBeVisible()
    const button=page.getByRole('button',{name:'Показать остановку на карте',exact:true})
    const before=await camera(page), calls=api.calls.length
    await button.hover(); await button.focus()
    expect(await button.evaluate(element=>parseFloat(getComputedStyle(element).outlineWidth))).toBeGreaterThanOrEqual(2)
    expect(await camera(page)).toEqual(before)
    await expect(page.locator('.city-map-object')).toHaveCount(0)
    await button.press('Enter'); await fitsSelection(page)
    await expect(page.locator('.city-map-object')).toContainText('150 м · по прямой')
    const park=page.getByRole('article').filter({has:page.getByRole('heading',{name:'Ближайший парк',exact:true})}).getByRole('button')
    await park.press('Enter'); await fitsSelection(page)
    await expect(park).toHaveAttribute('aria-pressed','true')
    expect(await page.locator('.map-address-label.is-selected').evaluate(label=>{
        const a=label.getBoundingClientRect(),root=label.closest('.city-map')
        return [...root.querySelectorAll('.city-map-legend,.city-map-toolbar,.city-map-overview')].every(element=>{const b=element.getBoundingClientRect();return !b.width||!b.height||a.right<=b.left||a.left>=b.right||a.bottom<=b.top||a.top>=b.bottom})
    })).toBe(true)
    expect(await page.evaluate(async()=> (await window.__smokeMapIn('.address-map').getSource('analysis-object-selection').getData()).features)).toEqual(profile(places.a).map.area_layers.parks.data.features)
    await expect(page.locator('.city-map-object')).toContainText('200 м · до контура по прямой')
    await expect(page.locator('.city-map-object')).toContainText('часть контура')
    const chosen=await camera(page)
    for(const theme of ['Тёмная','Улицы','Светлая']) { await page.getByRole('button',{name:theme,exact:true}).click(); expect(await camera(page)).toEqual(chosen) }
    await page.getByRole('button',{name:/Слои 2 включено/}).click()
    expect(await camera(page)).toEqual(chosen)
    await page.getByRole('button',{name:/Слои 2 включено/}).click()
    await page.getByRole('button',{name:'Снять выделение объекта слоя',exact:true}).click()
    expect(await camera(page)).toEqual(chosen)
    await expect(park).toHaveAttribute('aria-pressed','false')
    await expect(page.locator('.address-map canvas')).toBeFocused()
    await page.getByRole('button',{name:'К радиусу 500 м',exact:true}).click()
    expect(api.calls.length).toBe(calls)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('map selection keeps distinct equal names and opens the corresponding stop disclosure without hover selection',async({page,api})=>{
    const data=profile(places.a)
    data.blocks.transport.data.stops_in_radius.forEach(s=>s.name='Одинаковое имя')
    await page.route('**/profile?*',route=>route.fulfill({json:data}))
    await page.goto(profileUrl)
    await expect(page.getByRole('heading',{name:places.a.label,exact:true})).toBeVisible()
    await page.getByRole('button',{name:/Слои 0 включено/}).click()
    await page.getByRole('checkbox',{name:'Остановки',exact:true}).check()
    await page.getByRole('button',{name:/Слои 1 включено/}).click()
    await settled(page)
    const stop=data.map.stops_in_radius.at(-1)
    await page.locator('.address-map canvas').scrollIntoViewIfNeeded()
    const point=await page.evaluate(stop=>{const m=window.__smokeMapIn('.address-map'),p=m.project([stop.lon,stop.lat]),r=m.getCanvas().getBoundingClientRect();return {x:r.left+p.x,y:r.top+p.y}},stop)
    await page.mouse.move(point.x,point.y)
    await expect(page.locator('.city-map-object')).toHaveCount(0)
    await page.mouse.click(point.x,point.y)
    await expect(page.locator('.city-map-object')).toHaveAttribute('data-selected-id',String(stop.id))
    await fitsSelection(page)
    await expect(page.getByRole('list',{name:'Остальные остановки профиля'}).getByRole('button',{pressed:true})).toHaveCount(1)
    const old=await camera(page)
    await page.getByRole('button',{name:'Снять выделение остановки',exact:true}).click()
    expect(await camera(page)).toEqual(old)
})
test('comparison exact selections survive mobile side changes with shared scale and independent centers',async({page,api})=>{
    await page.goto(comparisonUrl());await ready(page)
    const calls=api.calls.length
    await page.getByRole('button',{name:'Ближайший парк: на карте А',exact:true}).click();await mapReady(page)
    await fitsSelection(page,'#compare-map-left')
    const a=await camera(page,'#compare-map-left')
    await page.getByRole('button',{name:'К результатам',exact:true}).click()
    await page.getByRole('button',{name:'Ближайший парк: на карте Б',exact:true}).click();await mapReady(page)
    await fitsSelection(page,'#compare-map-right')
    await expect(page.locator('#compare-map-left .city-map-object')).toHaveAttribute('data-selected-id',`${places.a.id}-parks`)
    await expect(page.locator('#compare-map-right .city-map-object')).toHaveAttribute('data-selected-id',`${places.b.id}-parks`)
    expect((await camera(page,'#compare-map-left')).center).toEqual(a.center)
    const centers=await page.evaluate(()=>['left','right'].map(side=>{const m=window.__smokeMapIn(`#compare-map-${side}`);return {center:m.getCenter().toArray(),zoom:m.getZoom()}}))
    expect(centers[0].zoom).toBeCloseTo(centers[1].zoom,8)
    expect(centers[0].center).not.toEqual(centers[1].center)
    expect(api.calls.length).toBe(calls)
})

