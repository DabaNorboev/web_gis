test('explicit choice before the real map load is retained when its source becomes ready',async({page,api})=>{
    let release
    const gate=new Promise(resolve=>{release=resolve})
    await page.route('**/smoke-background.json',async route=>{await gate;await route.continue()})
    await page.goto(profileUrl,{waitUntil:'domcontentloaded'})
    await expect(page.getByRole('heading',{name:places.a.label,exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Показать остановку на карте',exact:true}).click()
    await expect(page.locator('.city-map-object')).toContainText('Выбранная остановка')
    release()
    await fitsSelection(page)
    await expect(page.locator('.city-map-object')).toHaveAttribute('data-selected-id',String(profile(places.a).blocks.transport.data.nearest_stop.id))
})
